// pak.h — 資源包：遊戲檔放不下的大圖（背景、角色動畫）另外放在一個二進位檔
//
// 為什麼要資源包？
//   遊戲檔是 Lua 文字檔，圖片用 base64 塞進去，每張圖都會一直佔著記憶體。
//   固定視角的遊戲每個鏡頭一張 320×240 背景，一個章節就有幾十張，
//   全部塞進遊戲檔，Pico 的 520 KB 記憶體根本放不下。
//   資源包放在遊戲檔旁邊（game.lua + game.pak），要用哪張才讀哪張，
//   換房間時舊的背景直接被新的蓋掉，記憶體裡永遠只有「現在這一張」。
//
// 檔案格式（第 1 版，所有整數都是 little-endian）：
//   開頭 48 bytes：
//     "CPAK"            4 bytes
//     版本 u32          1
//     項目數 u32
//     內容指紋 32 bytes  打包工具算好的 SHA-256（見下方「和重播的關係」）
//     保留 u32
//   目錄：每個項目 48 bytes
//     名稱 32 bytes（UTF-8，不足補 0）、種類 u32、位置 u32（從檔案開頭算）、大小 u32、保留 u32
//   接著是各項目的資料。種類：
//     1 背景 PAK_BG
//         u16 寬（320）、u16 高（240）、u16 顏色數 n（最多 128）、n × RGB
//         寬 × 高 個顏色編號（0 .. n-1；載入時變成調色盤 128 + i）
//         u16 深度寬、u16 深度高（160、120；0、0 代表沒有深度）
//         深度：RLE，一對一對的（個數 u8 1–255、值 u8），值的單位是 8 公分，0 = 沒有東西擋
//     2 角色 PAK_SPRITES（一組動畫格）
//         u16 格數、之後每格 12 bytes：u16 寬、u16 高、s16 ox、s16 oy、u32 位置（從這個項目開頭算）
//         (ox, oy)：這格的左上角相對於「腳底的點」的位置（像素，原尺寸）
//         每格的像素：寬 × 高 個顏色編號，0 = 透明。顏色已經是全域調色盤的編號（16–127）
//     3 調色盤 PAK_PAL
//         u16 第一色、u16 顏色數、顏色數 × RGB
//     4 資料 PAK_DATA：任意 bytes（文字、表格），遊戲用 pakdata() 拿到字串
//
// 調色盤怎麼分（規格建議，引擎只強制背景用 128–255）：
//   0–15     引擎預設 16 色
//   16–127   角色、道具圖示、介面（整個遊戲共用，打包工具一起量化）
//   128–255  目前的背景（換背景就換掉）
//
// 和重播的關係：
//   遊戲畫面取決於資源包的內容，所以資源包換了，舊的重播就不能用。
//   遊戲指紋 = SHA-256(遊戲檔的指紋 + 資源包的內容指紋)（沒有資源包時和以前一樣）。
//   內容指紋是打包工具寫在檔頭的，引擎不重算：Pico 每次開遊戲都把幾 MB 算一遍太慢。
//
// 平台的工作：在 engine_load() 之前呼叫 pak_set()，把整個檔案交給引擎。
//   資料由平台保管，遊戲執行期間不能釋放（之後 Pico 版改成從 SD 卡讀，Lua 這邊不用改）。

#ifndef PAK_H
#define PAK_H

#include <stddef.h>
#include <stdint.h>

#define PAK_BG      1
#define PAK_SPRITES 2
#define PAK_PAL     3
#define PAK_DATA    4

#define PAK_NAME_MAX 32
#define PAK_MAX_SPRITES 32   // 同時載入幾組角色動畫

struct lua_State;

// ---- 平台用 ----

// 交給引擎一個資源包（data 為 NULL 代表沒有）。格式不對回傳 1，並印出原因
int pak_set(const uint8_t *data, size_t len);

// ---- 引擎內部用 ----

// 目前資源包的內容指紋；沒有資源包回傳 NULL
const uint8_t *pak_sha(void);

// 換遊戲時：釋放所有角色動畫
void pak_reset(void);

// 註冊 Lua 函式（script.c 呼叫）
void pak_open_lua(struct lua_State *L);

#endif
