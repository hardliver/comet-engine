-- 文字測試：make check 用這個畫面比對網頁版和 Mac 版，並檢查字的點陣是否正確
-- 不要隨便改：tools/check_web.mjs 會檢查「野」畫在 (10, 10)、顏色 7

function _draw()
  cls(1)
  text("野生的 囤囤鼠 出現了！", 10, 10, 7)          -- 中文、全形標點、半形空白
  text("HP 28/45  Lv12  ABCgjy", 10, 30, 10)       -- 英數字是比例字型，g j y 有下伸部
  text(12345, 10, 50, 11)                          -- 數字也可以直接畫
  text("第一行\n第二行", 10, 70, 7)                  -- 換行
  text("沒有的字：🙂", 10, 110, 8)                  -- 字型裡沒有的字畫成方框
  local w = textw("置中的字")
  text("置中的字", (SCREEN_W - w) // 2, 140, 12)
  rect((SCREEN_W - w) // 2, 156, w, 1, 12)         -- 底線：寬度要剛好等於 textw
  camera(-100, 0)
  text("相機", 10, 180, 9)                          -- 受相機影響：實際畫在 x = 110
  camera()
end
